"""SQLAlchemy tables for sensors, readings, and recommendation decisions."""

from datetime import datetime
from typing import Optional, Any

from sqlalchemy import (
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
    CheckConstraint,
    JSON,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from .database import Base



class SensorPoint(Base):
    __tablename__ = "sensor_points"

    sensor_point_id: Mapped[int] = mapped_column(
        primary_key=True,
        autoincrement=True,
    )

    sensor_code: Mapped[str] = mapped_column(
        String(100),
        unique=True,
        nullable=False,
        index=True,
    )

    trend_column: Mapped[str] = mapped_column(
        String(150),
        unique=True,
        nullable=False,
    )

    display_name: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )

    measurement_property: Mapped[Optional[int]] = mapped_column(
        Integer,
        nullable=True,
    )

    category: Mapped[Optional[str]] = mapped_column(
        String(100),
        nullable=True,
    )

    priority: Mapped[Optional[str]] = mapped_column(
        String(10),
        nullable=True,
    )

    why_selected: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )

    dashboard_feature: Mapped[Optional[str]] = mapped_column(
        String(150),
        nullable=True,
    )

    raw_unit: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
    )

    display_unit: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
    )

    scale_factor: Mapped[float] = mapped_column(
        Float,
        default=1.0,
        nullable=False,
    )

    sign_convention: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )

    data_type: Mapped[Optional[str]] = mapped_column(
        String(50),
        nullable=True,
    )

    location: Mapped[Optional[str]] = mapped_column(
        String(150),
        nullable=True,
    )

    is_selected: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        nullable=False,
    )


class SensorReading(Base):

    __tablename__ = "sensor_readings"

    reading_id: Mapped[int] = mapped_column(
        primary_key=True,
        autoincrement=True,
    )

    sensor_point_id: Mapped[int] = mapped_column(
        ForeignKey("sensor_points.sensor_point_id"),
        nullable=False,
        index=True,
    )

    reading_time: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        index=True,
    )

    value: Mapped[Optional[float]] = mapped_column(
        Float,
        nullable=True,
    )

    __table_args__ = (
        UniqueConstraint(
            "sensor_point_id",
            "reading_time",
            name="unique_sensor_reading",
        ),
    )

class Recommendation(Base):
    """Persisted recommendation generated by the rule/AI service."""

    __tablename__ = "recommendations"

    __table_args__ = (
        UniqueConstraint(
            "recommendation_key",
            "recommendation_version",
            name="uq_recommendations_key_version",
        ),
    )

    recommendation_id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        autoincrement=True,
    )

    recommendation_key: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
    )

    recommendation_version: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=1,
    )

    recommendation_time: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    recommendation_text: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    reason: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    status: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        default="pending",
    )

    target_sensor_point_id: Mapped[int | None] = mapped_column(
        ForeignKey("sensor_points.sensor_point_id"),
        nullable=True,
        index=True,
    )

    current_value: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    recommended_value: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    expected_savings_kwh: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
    )

    category: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )

    priority: Mapped[str | None] = mapped_column(
        String(20),
        nullable=True,
    )

    recommendation_snapshot: Mapped[dict[str, Any] | None] = mapped_column(
        JSON,
        nullable=True,
    )


class RecommendationDecision(Base):
    __tablename__ = "recommendation_decisions"

    __table_args__ = (
        CheckConstraint(
            "action IN ('approved', 'rejected')",
            name="ck_recommendation_decisions_action",
        ),
    )

    decision_id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        autoincrement=True,
    )

    recommendation_id: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        index=True,
    )

    recommendation_version: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=1,
    )

    stored_recommendation_id: Mapped[int | None] = mapped_column(
        ForeignKey("recommendations.recommendation_id"),
        nullable=True,
        index=True,
    )

    action: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
    )

    comment: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    operator_label: Mapped[str] = mapped_column(
        String(200),
        nullable=False,
    )

    recommendation_snapshot: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
    )

    idempotency_key: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        unique=True,
        index=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    # Active decisions control the current recommendation status. Resetting a
    # decision marks it inactive instead of deleting the audit record.
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
        server_default="true",
        index=True,
    )

    reverted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    reverted_by: Mapped[str | None] = mapped_column(
        String(200),
        nullable=True,
    )

    revert_comment: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )
